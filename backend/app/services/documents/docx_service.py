"""DOCX export service using python-docx."""

import io
import logging

from docx import Document
from docx.shared import Pt, Inches, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

logger = logging.getLogger("societyos.documents.docx")

SECTION_NAMES = {
    "executive_summary": "Executive Summary",
    "objectives": "Objectives",
    "scope": "Scope",
    "schedule": "Schedule",
    "resources": "Resources",
    "expected_outcomes": "Expected Outcomes",
    "risk_assessment": "Risk Assessment",
    "appendices": "Appendices",
}


def generate_proposal_docx(
    title: str,
    society: str,
    university: str,
    event_type: str,
    event_date: str,
    sections: dict,
) -> bytes:
    """Generate a professional proposal DOCX."""
    doc = Document()

    # Title
    title_para = doc.add_heading(title, level=0)
    title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER

    # Metadata
    meta = doc.add_paragraph()
    meta.alignment = WD_ALIGN_PARAGRAPH.CENTER
    meta_run = meta.add_run(f"{society} | {university}\n{event_type.capitalize()} | {event_date or 'TBD'}")
    meta_run.font.size = Pt(10)
    meta_run.font.color.rgb = RGBColor(100, 116, 139)

    doc.add_paragraph()  # spacer

    # Sections
    for key, label in SECTION_NAMES.items():
        content = sections.get(key, "")
        if content:
            doc.add_heading(label, level=1)
            for para_text in content.split("\n\n"):
                if para_text.strip():
                    doc.add_paragraph(para_text.strip())

    # Footer note
    doc.add_paragraph()
    footer = doc.add_paragraph("Generated by SocietyOS AI")
    footer.runs[0].font.size = Pt(8)
    footer.runs[0].font.color.rgb = RGBColor(148, 163, 184)
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER

    buffer = io.BytesIO()
    doc.save(buffer)
    return buffer.getvalue()
