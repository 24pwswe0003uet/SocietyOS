"""PDF export service using WeasyPrint."""

import io
import logging

logger = logging.getLogger("societyos.documents.pdf")

PROPOSAL_TEMPLATE = """
<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<style>
  body {{ font-family: 'Helvetica Neue', Arial, sans-serif; font-size: 11pt; color: #1e293b; line-height: 1.6; margin: 40px; }}
  h1 {{ color: #4f46e5; font-size: 22pt; border-bottom: 2px solid #4f46e5; padding-bottom: 8px; margin-bottom: 16px; }}
  h2 {{ color: #334155; font-size: 14pt; margin-top: 24px; margin-bottom: 8px; }}
  .header {{ text-align: center; margin-bottom: 32px; }}
  .header h1 {{ border: none; }}
  .header .meta {{ color: #64748b; font-size: 10pt; }}
  .section {{ margin-bottom: 20px; }}
  .footer {{ position: fixed; bottom: 20px; left: 40px; right: 40px; text-align: center; font-size: 8pt; color: #94a3b8; border-top: 1px solid #e2e8f0; padding-top: 8px; }}
  @page {{ size: A4; margin: 25mm; }}
</style>
</head>
<body>
<div class="header">
  <h1>{title}</h1>
  <p class="meta">{society} &middot; {university}</p>
  <p class="meta">{event_type} &middot; {event_date}</p>
</div>
{sections_html}
<div class="footer">Generated by SocietyOS AI</div>
</body>
</html>
"""


def generate_proposal_pdf(
    title: str,
    society: str,
    university: str,
    event_type: str,
    event_date: str,
    sections: dict,
) -> bytes:
    """Generate a professional proposal PDF."""
    try:
        from weasyprint import HTML
    except ImportError:
        logger.warning("WeasyPrint not available, generating simple HTML fallback")
        return _html_fallback(title, society, university, event_type, event_date, sections)

    section_names = {
        "executive_summary": "Executive Summary",
        "objectives": "Objectives",
        "scope": "Scope",
        "schedule": "Schedule",
        "resources": "Resources",
        "expected_outcomes": "Expected Outcomes",
        "risk_assessment": "Risk Assessment",
        "appendices": "Appendices",
    }

    sections_html = ""
    for key, label in section_names.items():
        content = sections.get(key, "")
        if content:
            paragraphs = content.replace("\n\n", "</p><p>").replace("\n", "<br>")
            sections_html += f'<div class="section"><h2>{label}</h2><p>{paragraphs}</p></div>'

    html_str = PROPOSAL_TEMPLATE.format(
        title=title,
        society=society,
        university=university,
        event_type=event_type.capitalize(),
        event_date=event_date or "TBD",
        sections_html=sections_html,
    )

    pdf_bytes = HTML(string=html_str).write_pdf()
    return pdf_bytes


def _html_fallback(title, society, university, event_type, event_date, sections) -> bytes:
    """Return HTML as bytes when WeasyPrint is not available."""
    html = PROPOSAL_TEMPLATE.format(
        title=title, society=society, university=university,
        event_type=event_type, event_date=event_date or "TBD",
        sections_html="".join(f"<h2>{k}</h2><p>{v}</p>" for k, v in sections.items() if v),
    )
    return html.encode("utf-8")


SPONSORSHIP_TEMPLATE = """
<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<style>
  body {{ font-family: 'Helvetica Neue', Arial, sans-serif; font-size: 11pt; color: #1e293b; line-height: 1.6; margin: 40px; }}
  h1 {{ color: #4f46e5; font-size: 22pt; text-align: center; }}
  h2 {{ color: #334155; font-size: 14pt; margin-top: 28px; border-bottom: 1px solid #e2e8f0; padding-bottom: 6px; }}
  .meta {{ text-align: center; color: #64748b; font-size: 10pt; margin-bottom: 24px; }}
  .tier {{ border: 1px solid #e2e8f0; border-radius: 8px; padding: 16px; margin-bottom: 16px; }}
  .tier-gold {{ border-color: #f59e0b; background: #fffbeb; }}
  .tier-silver {{ border-color: #94a3b8; background: #f8fafc; }}
  .tier-bronze {{ border-color: #d97706; background: #fef3c7; }}
  .tier h3 {{ margin: 0 0 8px; font-size: 13pt; }}
  .tier .amount {{ font-size: 16pt; font-weight: bold; color: #4f46e5; }}
  .benefits {{ list-style: none; padding: 0; }}
  .benefits li {{ padding: 4px 0; padding-left: 20px; position: relative; }}
  .benefits li::before {{ content: "✓"; position: absolute; left: 0; color: #059669; }}
  .footer {{ text-align: center; font-size: 8pt; color: #94a3b8; margin-top: 32px; border-top: 1px solid #e2e8f0; padding-top: 8px; }}
  @page {{ size: A4; margin: 25mm; }}
</style>
</head>
<body>
<h1>Sponsorship Package</h1>
<p class="meta">{title} &middot; {society}</p>

{audience_html}

<h2>Sponsorship Tiers</h2>
{tiers_html}

{emails_html}

<div class="footer">Generated by SocietyOS AI</div>
</body>
</html>
"""


def generate_sponsorship_pdf(
    title: str,
    society: str,
    tiers: list[dict],
    audience_summary: str | None = None,
    email_drafts: list[dict] | None = None,
) -> bytes:
    """Generate a professional sponsorship package PDF."""
    # Audience
    audience_html = ""
    if audience_summary:
        audience_html = f'<h2>Audience</h2><p>{audience_summary}</p>'

    # Tiers
    tier_classes = {"Gold": "tier-gold", "Silver": "tier-silver", "Bronze": "tier-bronze"}
    tiers_html = ""
    for tier in tiers:
        cls = tier_classes.get(tier.get("name", ""), "")
        benefits = "".join(f"<li>{b}</li>" for b in tier.get("benefits", []))
        tiers_html += f'''
        <div class="tier {cls}">
            <h3>{tier.get("name", "Tier")}</h3>
            <div class="amount">PKR {tier.get("amount", 0):,.0f}</div>
            <ul class="benefits">{benefits}</ul>
        </div>'''

    # Emails
    emails_html = ""
    if email_drafts:
        emails_html = "<h2>Outreach Email Templates</h2>"
        for draft in email_drafts:
            emails_html += f'''
            <div style="margin-bottom:16px;padding:12px;background:#f8fafc;border-radius:6px;">
                <p style="margin:0;font-weight:bold;">Industry: {draft.get("industry","General").capitalize()}</p>
                <p style="margin:4px 0;font-size:10pt;color:#64748b;">Subject A: {draft.get("subject_a","")}</p>
                <p style="margin:4px 0;font-size:10pt;color:#64748b;">Subject B: {draft.get("subject_b","")}</p>
                <p style="margin:8px 0 0;font-size:10pt;">{draft.get("body","")[:500]}</p>
            </div>'''

    html_str = SPONSORSHIP_TEMPLATE.format(
        title=title,
        society=society,
        audience_html=audience_html,
        tiers_html=tiers_html,
        emails_html=emails_html,
    )

    try:
        from weasyprint import HTML
        return HTML(string=html_str).write_pdf()
    except ImportError:
        return html_str.encode("utf-8")
